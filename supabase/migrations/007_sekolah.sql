-- 007: daftar sekolah (NPSN -> nama sekolah)
create table if not exists public.sekolah (
  npsn text primary key check (npsn ~ '^[0-9]{8}$'),
  nama text not null,
  dibuat_at timestamptz not null default now()
);

-- Seperti tabel lain: dikunci, hanya server (service role) yang boleh mengakses.
alter table public.sekolah enable row level security;

